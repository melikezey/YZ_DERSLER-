arama_sorgusu = input("Aramak istediğiniz ürünü girin: ").strip().casefold()

# Türkçe karakterleri koruyarak eşleşme yap
arama_kelime = arama_sorgusu
aranacak_kelimeler = {arama_kelime}

for kelime, alternatifler in es_anlamli.items():
    if kelime in arama_kelime:
        aranacak_kelimeler.add(kelime)
        aranacak_kelimeler.update(alternatifler)

bulunan_urunler = []

for urun in urunler:
    urun_kucuk = urun.casefold()

    # Tam arama veya ilgili kelimelerden biriyle eşleşme
    if any(kelime in urun_kucuk for kelime in aranacak_kelimeler):
        bulunan_urunler.append(urun)

print("\nArama Sorgusu:", arama_sorgusu)

if bulunan_urunler:
    print("Bulunan Eşleşen Ürünler:")
    for urun in bulunan_urunler:
        print("-", urun)

    print("\nToplam bulunan ürün:", len(bulunan_urunler))
else:
    print("Aradığınız ürün bulunamadı.")
    print("Başka bir kelimeyle aramayı deneyebilirsiniz.")
